  /**
   * Walks the CIFF heap. Calls visit(rec) for every record:
   * rec = { type, id (type & 0x3fff), dataType, len, off (absolute), inRecord, depth }
   */
  function walkCiff(r, offset, length, depth, visit) {
    if (depth > 8 || length < 4) return;
    const tboff = r.u32(offset + length - 4) + offset;
    if (!r.inRange(tboff, 2)) return;
    let nrecs = r.u16(tboff);
    if (nrecs < 1 || nrecs > 1000 || !r.inRange(tboff + 2, nrecs * 10)) return;
    for (let i = 0; i < nrecs; i++) {
      const p = tboff + 2 + i * 10;
      const type = r.u16(p);
      const inRecord = (type & 0xc000) === 0x4000;
      const len = r.u32(p + 2);
      const off = inRecord ? p + 2 : offset + r.u32(p + 6);
      const rec = { type, id: type & 0x3fff, dataType: type & 0x3800, len: inRecord ? 8 : len, raw32: len, off, inRecord, depth };
      if (!inRecord && (off >= r.size || off + len > r.size)) continue;
      const isDir = !inRecord && (rec.dataType === 0x2800 || rec.dataType === 0x3000);
      visit(rec, isDir);
      if (isDir) walkCiff(r, off, len, depth + 1, visit);
    }
  }

  RL.parseCiff = function (u8) {
    const r = new RL.Reader(u8, true);
    if (r.ascii(6, 8) !== 'HEAPCCDR') return null;
    if (u8[0] === 0x4d) r.le = false;
    const hlen = r.u32(2);
    const recs = [];
    walkCiff(r, hlen, r.size - hlen, 0, (rec) => recs.push(rec));
    return { r, hlen, recs };
  };

  // ------------------------------------------------------- canon_load_raw
  function canonHasLowbits(u8, base) {
    // In Canon compressed data, 0xff is always followed by 0x00.
    let ret = 1;
    const end = Math.min(base + 0x4000 - 1, u8.length - 1);
    for (let i = base + 540; i < end; i++) {
      if (u8[i] === 0xff) {
        if (u8[i + 1]) return 1;
        ret = 0;
      }
    }
    return ret;
  }

  /**
   * base   - file offset where the raw data block starts (dcraw assumes the
   *          block sits right after the 26 byte header, i.e. file offset 0)
   * table  - decoder table index from tag 0x1835
   * Returns { lowbits, maxValue }.
   */
  RL.decodeCanonCrw = function (u8, base, raw, rawW, rawH, table, progress) {
    if (table > 2) table = 2;
    if (!(table >= 0)) table = 0;
    const h1 = RL.makeHuffDecoder(FIRST_TREE[table], 0);
    const h2 = RL.makeHuffDecoder(SECOND_TREE[table], 0);
    const lowbits = canonHasLowbits(u8, base);
    const end = u8.length;
    let pos = base + 540 + lowbits * ((rawH * rawW / 4) | 0);

    let bitbuf = 0, vbits = 0, reset = 0;
    function fill(n) {
      while (!reset && vbits < n) {
        if (pos >= end) break;
        const c = u8[pos++];
        if (c === 0xff) {
          const c2 = pos < end ? u8[pos++] : 0;
          if (c2) { reset = 1; break; }
        }
        bitbuf = (bitbuf << 8) | c;
        vbits += 8;
      }
    }
    function getbits(n) {
      if (n === 0 || vbits < 0) return 0;
      fill(n);
      const v = vbits === 0 ? 0 : ((bitbuf << (32 - vbits)) >>> (32 - n));
      vbits -= n;
      return v;
    }
    function gethuff(h) {
      const n = h.max;
      if (n === 0 || vbits < 0) return 0;
      fill(n);
      const idx = vbits === 0 ? 0 : ((bitbuf << (32 - vbits)) >>> (32 - n));
      const e = h.table[idx];
      vbits -= e >> 8;
      return e & 0xff;
    }

    const diffbuf = new Int32Array(64);
    const base2 = new Int32Array(2);
    let carry = 0, pnum = 0;
    for (let row = 0; row < rawH; row += 8) {
      const pixel = row * rawW;
      const nblocks = (Math.min(8, rawH - row) * rawW) >> 6;
      for (let block = 0; block < nblocks; block++) {
        diffbuf.fill(0);
        for (let i = 0; i < 64; i++) {
          const leaf = gethuff(i > 0 ? h2 : h1);
          if (leaf === 0 && i) break;
          if (leaf === 0xff) continue;
          i += leaf >> 4;
          const len = leaf & 15;
          if (len === 0) continue;
          let diff = getbits(len);
          if ((diff & (1 << (len - 1))) === 0) diff -= (1 << len) - 1;
          if (i < 64) diffbuf[i] = diff;
        }
        diffbuf[0] += carry;
        carry = diffbuf[0];
        const o = pixel + (block << 6);
        for (let i = 0; i < 64; i++) {
          if (pnum++ % rawW === 0) base2[0] = base2[1] = 512;
          base2[i & 1] += diffbuf[i];
          raw[o + i] = base2[i & 1];
        }
      }
      if (lowbits) {
        let lp = base + 26 + ((row * rawW / 4) | 0);
        let prow = pixel;
        const n = rawW * 2;
        for (let i = 0; i < n; i++) {
          const c = u8[lp++];
          for (let rr = 0; rr < 8; rr += 2, prow++) {
            let val = (raw[prow] << 2) + ((c >> rr) & 3);
            if (rawW === 2672 && val < 512) val += 2;
            raw[prow] = val;
          }
        }
      }
      if (progress && (row & 63) === 0) progress(row / rawH);
    }
    return { lowbits, maxValue: lowbits ? 0xfff : 0x3ff };
  };
